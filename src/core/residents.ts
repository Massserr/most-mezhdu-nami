export function getResidentViews(state: GameState) {
  return RESIDENTS.map((person) => {
    const time = getRoute(state, person.home, person.service).time;
    const waiting = person.service === 'workshop' && state.day < 6;
    const status = waiting
      ? 'waiting'
      : time === null
        ? 'blocked'
        : time <= person.limit
          ? 'good'
          : 'long';
    return {
      ...person,
      time,
      status,
      quote: person[status],
      statusText: waiting
        ? 'Готовится к открытию'
        : time === null
          ? 'Нет проезда'
          : time <= person.limit
            ? 'Путь стал удобнее'
            : 'Путь ещё долгий',
    };
  });
}

export function getEnding(state: GameState): string[] {
  const residents = getResidentViews(state);
  const helped = residents.filter((p) => p.status === 'good');
  const opening =
    helped.length >= 3
      ? 'В воскресенье у реки снова встретились соседи с обоих берегов. За неделю появились дороги, которыми завтра воспользуются без торжественных речей: просто потому, что стало удобнее жить.'
      : helped.length
        ? 'Не все планы удалось закончить. Но у новых дорог уже есть свои пассажиры, и поселение увидело, с чего можно начать перемены.'
        : 'Неделя закончилась, а часть дорог всё ещё ждёт работы. Теперь ясно, где помощь нужна прежде всего. У Берёзовки остаётся возможность попробовать снова.';
  return [
    opening,
    ...residents.map((p) => `${p.name}: «${p.quote}»`),
    state.completedTasks.includes('resilience')
      ? 'Поселение встретило дождь с двумя действующими переходами. Забота о запасном пути стала заботой о каждом, кому он может понадобиться.'
      : 'Резервные переходы и мокрые дороги ещё требуют внимания. Эту работу стоит продолжить.',
  ];
}
